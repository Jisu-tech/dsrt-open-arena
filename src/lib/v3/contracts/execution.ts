/**
 * DSRT Open Arena V3 — Execution Contracts
 * 
 * Defines execution plans, execution steps, and subtask structures.
 * An execution plan is the decomposition of a task into ordered steps,
 * each of which may produce one or more model invocations.
 * 
 * Phase 1 uses simple single-step execution plans for direct tasks.
 * Multi-step plans are implemented in Phase 2+.
 * 
 * @module v3/contracts/execution
 */

import type {
  TaskId,
  ExecutionStepId,
  WorkspaceId,
  InvocationId,
} from './identifiers';
import type {
  ISOTimestamp,
  DurationMs,
  AuditFields,
  MonetaryValue,
} from './metadata';
import {
  ExecutionStrategy,
  TaskState,
  InvocationPurpose,
} from './enums';

// ─────────────────────────────────────────────
// Execution Plan
// ─────────────────────────────────────────────

/**
 * An execution plan describes how a task will be carried out.
 * In Phase 1, all tasks get a single-step direct plan.
 */
export interface ExecutionPlan {
  readonly taskId: TaskId;
  readonly workspaceId: WorkspaceId;

  /** Selected strategy for execution. */
  readonly strategy: ExecutionStrategy;

  /** Ordered list of steps. */
  readonly steps: readonly ExecutionStep[];

  /** Whether this plan was generated by a model or deterministic logic. */
  readonly plannedBy: 'deterministic' | 'model_assisted';

  /** Estimated total cost for the plan. null if not estimated. */
  readonly estimatedTotalCost: MonetaryValue | null;

  /** When the plan was created. */
  readonly plannedAt: ISOTimestamp;
}

// ─────────────────────────────────────────────
// Execution Step
// ─────────────────────────────────────────────

/**
 * Status of an individual execution step.
 */
export type ExecutionStepStatus =
  | 'pending'
  | 'running'
  | 'completed'
  | 'failed'
  | 'skipped'
  | 'cancelled';

/**
 * A single step in an execution plan.
 * Each step produces zero or more model invocations.
 */
export interface ExecutionStep extends AuditFields {
  readonly id: ExecutionStepId;
  readonly taskId: TaskId;
  readonly workspaceId: WorkspaceId;

  /** Step ordering within the plan (0-indexed). */
  readonly sequence: number;

  /** What this step does. */
  readonly purpose: InvocationPurpose;

  /** Human-readable description of this step. */
  readonly description: string;

  /** Current status. */
  readonly status: ExecutionStepStatus;

  /** IDs of invocations produced by this step. */
  readonly invocationIds: readonly InvocationId[];

  /** Step dependencies — indices of steps that must complete before this one starts. */
  readonly dependsOn: readonly number[];

  /** Whether this step can be skipped if the task is Class 0. */
  readonly skippable: boolean;

  /** Estimated cost for this step. null if not estimated. */
  readonly estimatedCost: MonetaryValue | null;

  /** Actual cost after completion. null if not completed. */
  readonly actualCost: MonetaryValue | null;

  /** When execution of this step started. */
  readonly startedAt: ISOTimestamp | null;

  /** When execution of this step completed. */
  readonly completedAt: ISOTimestamp | null;

  /** Duration in milliseconds. */
  readonly durationMs: DurationMs | null;

  /** Error information if step failed. */
  readonly error: string | null;
}

// ─────────────────────────────────────────────
// Creation Inputs
// ─────────────────────────────────────────────

/**
 * Input for creating an execution step.
 */
export interface CreateExecutionStepInput {
  readonly taskId: TaskId;
  readonly workspaceId: WorkspaceId;
  readonly sequence: number;
  readonly purpose: InvocationPurpose;
  readonly description: string;
  readonly dependsOn?: readonly number[];
  readonly skippable?: boolean;
  readonly estimatedCost?: MonetaryValue;
}

// ─────────────────────────────────────────────
// Direct Execution Plan Factory
// ─────────────────────────────────────────────

/**
 * Creates a single-step direct execution plan.
 * Used for Class 0 tasks and Phase 1 where all tasks are direct.
 */
export function createDirectExecutionPlan(
  taskId: TaskId,
  workspaceId: WorkspaceId,
  stepId: ExecutionStepId,
): ExecutionPlan {
  const now = new Date().toISOString();
  return {
    taskId,
    workspaceId,
    strategy: ExecutionStrategy.DIRECT,
    steps: [
      {
        id: stepId,
        taskId,
        workspaceId,
        sequence: 0,
        purpose: InvocationPurpose.PRIMARY_GENERATION,
        description: 'Direct model invocation — no amplification',
        status: 'pending',
        invocationIds: [],
        dependsOn: [],
        skippable: false,
        estimatedCost: null,
        actualCost: null,
        startedAt: null,
        completedAt: null,
        durationMs: null,
        error: null,
        createdAt: now,
        updatedAt: now,
      },
    ],
    plannedBy: 'deterministic',
    estimatedTotalCost: null,
    plannedAt: now,
  };
}